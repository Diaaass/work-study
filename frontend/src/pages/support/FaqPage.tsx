function AccordionItem({ question, answer }: FaqItem) {
  const [open, setOpen] = useState(false);
  return (
    <div className={`${styles.item} ${open ? styles.itemOpen : ''}`}>
      <button className={styles.question} onClick={() => setOpen(!open)}>
        <span>{question}</span>
        <span className={`${styles.chevron} ${open ? styles.chevronOpen : ''}`}>›</span>
      </button>
      {open && <div className={styles.answer}>{answer}</div>}
    </div>
  );
}

export default function FaqPage() {
  const { user } = useAuth();
  const isHR = user?.role === UserRole.HR;

  const roleItems = isHR ? FAQ_HR : FAQ_STUDENT;

  return (
    <div className={styles.page}>
      <div className={styles.header}>
        <h1 className={styles.title}>Часто задаваемые вопросы</h1>
        <p className={styles.subtitle}>Ответы на самые популярные вопросы о платформе</p>
      </div>

      <section className={styles.section}>
        <h2 className={styles.sectionTitle}>{isHR ? 'Для HR' : 'Для студентов'}</h2>
        {roleItems.map((item, i) => (
          <AccordionItem key={i} {...item} />
        ))}
      </section>

      <section className={styles.section}>
        <h2 className={styles.sectionTitle}>Общие вопросы</h2>
        {FAQ_COMMON.map((item, i) => (
          <AccordionItem key={i} {...item} />
        ))}
      </section>

      <div className={styles.cta}>
        <p>Не нашли ответ на свой вопрос?</p>
        <Link to="/support" className={styles.ctaLink}>Написать в поддержку</Link>
      </div>
    </div>
  );
}
